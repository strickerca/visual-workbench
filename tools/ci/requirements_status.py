#!/usr/bin/env python3
"""Link requirements to the automated tests that exercise them, and report status.

`docs/REQUIREMENTS.json` may give a requirement a `verified_by` list. Each entry
is `<test file path>::<test name>`. This script checks that every link points at
a tracked test file that still contains that test, and keeps the status table in
README.md generated from the requirements file.

A link means "this automated test exercises the requirement". It never changes
`verify_status`: requirements that need the phone, the laptop or the owner stay
unverified until that run happens.

Usage:
  requirements_status.py            check links and that the README table is current
  requirements_status.py --write    regenerate the README table
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS = ROOT / "docs" / "REQUIREMENTS.json"
README = ROOT / "README.md"
BEGIN = "<!-- requirements-status:begin (generated by tools/ci/requirements_status.py) -->"
END = "<!-- requirements-status:end -->"
PHASES = {0: "0 Hardware truth and setup", 1: "1 Markup core", 2: "2 First wins",
          3: "3 Precision, capture, sync", 4: "4 Remote edit", 5: "5 Verification and release"}
TEST_FILE = re.compile(
    r"(^|/)(tests?|androidTest|commonTest|jvmTest|desktopTest|androidDeviceTest|remoteIntegrationTest)/"
    r"|(_tests?|Test|\.test)\.(rs|kt|py|mjs)$|(^|/)test_[^/]+\.py$|_tests\.rs$")
DEVICE_METHODS = {"hardware", "manual"}


def tracked_files() -> set[str]:
    listed = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True)
    return set(listed.stdout.splitlines())


def check_links(requirements: list[dict]) -> list[str]:
    problems = []
    tracked = tracked_files()
    cache: dict[str, str] = {}
    for requirement in requirements:
        links = requirement.get("verified_by", [])
        if not isinstance(links, list) or any(not isinstance(link, str) for link in links):
            problems.append(f"{requirement['id']}: verified_by must be a list of strings")
            continue
        if len(set(links)) != len(links):
            problems.append(f"{requirement['id']}: duplicate verified_by entries")
        for link in links:
            path, separator, name = link.partition("::")
            if not separator or not path or not name:
                problems.append(f"{requirement['id']}: '{link}' is not <test file>::<test name>")
                continue
            if path not in tracked:
                problems.append(f"{requirement['id']}: {path} is not a tracked file")
                continue
            if not TEST_FILE.search(path):
                problems.append(f"{requirement['id']}: {path} is not a test file")
                continue
            if path not in cache:
                cache[path] = (ROOT / path).read_text(encoding="utf-8", errors="replace")
            if not re.search(r"(?<![A-Za-z0-9_])" + re.escape(name) + r"(?![A-Za-z0-9_])", cache[path]):
                problems.append(f"{requirement['id']}: test '{name}' not found in {path}")
    return problems


def table(requirements: list[dict]) -> str:
    rows = ["| Phase | Requirements | With an automated test | Fully verified | Still need the devices or the owner |",
            "| --- | --- | --- | --- | --- |"]
    totals = [0, 0, 0, 0]
    for phase, label in PHASES.items():
        scoped = [r for r in requirements if r["phase"] == phase and r["impl_status"] != "deferred"]
        linked = sum(1 for r in scoped if r.get("verified_by"))
        passed = sum(1 for r in scoped if r["verify_status"] == "passed")
        device = sum(1 for r in scoped if r["verify_status"] != "passed"
                     and DEVICE_METHODS & set(r["test_method"]))
        rows.append(f"| {label} | {len(scoped)} | {linked} | {passed} | {device} |")
        for index, value in enumerate((len(scoped), linked, passed, device)):
            totals[index] += value
    rows.append(f"| **All phases** | **{totals[0]}** | **{totals[1]}** | **{totals[2]}** | **{totals[3]}** |")
    deferred = sum(1 for r in requirements if r["impl_status"] == "deferred")
    rows.append("")
    rows.append(f"{deferred} deferred requirements are not counted. An automated test proves the software "
                "behaves as written; it is not a device result.")
    return "\n".join(rows)


def main() -> int:
    requirements = json.loads(REQUIREMENTS.read_text(encoding="utf-8"))["requirements"]
    problems = check_links(requirements)
    block = f"{BEGIN}\n{table(requirements)}\n{END}"
    readme = README.read_text(encoding="utf-8")
    if BEGIN not in readme or END not in readme:
        problems.append("README.md has no requirements-status block")
    else:
        current = readme[readme.index(BEGIN):readme.index(END) + len(END)]
        if "--write" in sys.argv[1:]:
            README.write_text(readme.replace(current, block), encoding="utf-8")
        elif current != block:
            problems.append("README.md status table is stale; run tools/ci/requirements_status.py --write")
    for problem in problems:
        print(problem)
    linked = sum(1 for r in requirements if r.get("verified_by"))
    print(f"REQUIREMENT LINKS: {'FAIL' if problems else 'OK'} ({linked} of {len(requirements)} requirements linked to tests)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
